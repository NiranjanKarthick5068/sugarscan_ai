def find_food_reference(query: str) -> dict | None:
    query = query.lower()
    for food in INDIAN_FOODS:
        name = str(food.get("food_name", ""))
        if name.lower() in query:
            return food
        aliases = food.get("aliases", [])
        if isinstance(aliases, list):
            for alias in aliases:
                if alias.lower() in query:
                    return food
    return None
